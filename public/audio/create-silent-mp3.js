// Creates a minimal valid MP3 file (1 second of silence)
// Using a pre-generated valid MP3 header + silent frame
import fs from 'fs';

// Minimal valid MP3 (MPEG-1 Layer 3, 44.1kHz, stereo, 128kbps, 1 frame ~26ms)
// This is a valid but very short MP3 file
const mp3Header = Buffer.from([
  0xFF, 0xFB, 0x90, 0x44,  // MP3 frame header
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
]);

// Repeat frame to make ~1 second (about 38 frames)
let mp3Data = Buffer.alloc(0);
for (let i = 0; i < 38; i++) {
  mp3Data = Buffer.concat([mp3Data, mp3Header]);
}

const tracks = [
  'chai-sutta-1.mp3',
  'chai-sutta-2.mp3',
  'chai-sutta-3.mp3',
  'weedy-valley-1.mp3',
  'weedy-valley-2.mp3',
  'weedy-valley-3.mp3',
  'panwadi-1.mp3',
  'panwadi-2.mp3',
  'panwadi-3.mp3'
];

tracks.forEach(track => {
  fs.writeFileSync(track, mp3Data);
  console.log(`Created ${track} (${mp3Data.length} bytes)`);
});
console.log('Done!');